export interface CharacterVisuals {
  skinTone: string;
  hairColor: string;
  hairStyle: 'hunter_hood' | 'sniper_helm' | 'flame_crest' | 'viking_helm' | 'shadow_mask' | 'storm_crown' | 'frost_circlet' | 'heavy_beret' | 'mystic_veil' | 'demon_horns' | 'cyber_optic' | 'magma_horns';
  shoulderPadColor: string;
  capeColor?: string;
  eyeColor: string;
  auraType: 'wind' | 'void' | 'fire' | 'shield' | 'poison' | 'lightning' | 'frost' | 'iron' | 'astral' | 'blood' | 'neon' | 'lava';
}

export interface Character {
  id: string;
  name: string;
  title: string;
  classType: string;
  avatarColor: string;
  tunicColor: string;
  accentColor: string;
  description: string;
  passiveName: string;
  passiveDesc: string;
  defaultWeaponId: string;
  baseHp: number;
  baseDamage: number;
  baseSpeed: number;
  attackSpeed: number;
  critChance: number;
  critMultiplier: number;
  unlockCost: number; // 0 for starter heroes, 300 - 1600 coins
  visuals: CharacterVisuals;
  innatePerks?: {
    fire?: boolean;
    poison?: boolean;
    ice?: boolean;
    lightning?: boolean;
    piercing?: boolean;
    shield?: boolean;
    multishot?: boolean;
    familiar?: boolean;
    bloodthirst?: number; // % heal on kill
  };
}

